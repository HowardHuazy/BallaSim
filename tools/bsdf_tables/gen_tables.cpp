// Generator of src/render/shade/bsdf_tables.inc (p2f.md §4.3, F111; CMake target balla_bsdf_gen_tables).
//
//   balla_bsdf_gen_tables --out FILE [--check FILE] [--report DIR] [--threads N]
//
// Computes the node values of every table in fp64 (tables_ref.h: A and B by quadrature; ltc_ref.h: the LTC fit), fits
// the C2 cubic B-spline coefficients and writes them as fp32 with the shortest round-trip spelling, so the output
// depends on nothing but IEEE arithmetic: each r-row is computed by one thread, the rows are joined in order, and a
// regeneration is bitwise equal (--check FILE compares the output with FILE and exits 1 when they differ; the ctest
// bsdf_tables_regen). Every run also checks T-TAB's node rows and exits 1 when one fails: the splines reproduce the
// node values (A, B and the LTC entries within 1e-6 relative to max(1, |value|)), the LTC's normal-view nodes are
// isotropic (m00 = 1, m02 = m20 = 0 exactly, and the odd splines 0 there), and no fit failed. --report DIR also writes
// T-TAB's records: every node's spline error, every cell centre against fp64 quadrature, and the bilinear-against-
// spline kink per cell (F111's magnitude), as cells.csv and summary.txt, a dense sweep of the near-mirror rows
// (r < 0.2) over the grazing views a shading point can reach (mu_v,e >= delta_mu / 2), as near_mirror.csv, and the
// LTC's error measures at every cell centre (ltc_ref.h fit_metrics through the splines) as ltc_cells.csv and
// ltc_rows.csv.
